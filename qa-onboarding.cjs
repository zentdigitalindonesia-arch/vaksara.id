const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({ channel: process.env.QA_BROWSER || 'msedge', headless: true });
  try {
    const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
    const errors = [];
    page.on('pageerror', e => errors.push(e.message));
    const base = pathToFileURL(path.join(__dirname, 'dist/index.html')).href + '#/';
    let passed = 0;
    const ok = (label, value = true) => { assert.ok(value, label); passed++; console.log('PASS', label); };
    const click = name => page.getByRole('button', { name, exact: true }).click();
    const heading = text => page.getByRole('heading', { name: text, exact: true }).waitFor();
    const fits = () => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth);
    await page.goto(base + 'beranda');
    await page.getByRole('button', { name: 'Mulai Rencanakan Pernikahan', exact: true }).first().click();
    await page.getByText('Anda sedang melihat acara contoh.', { exact: false }).first().waitFor();
    ok('kunjungan pertama langsung berisi acara contoh');
    page.once('dialog', d => d.accept());
    await page.getByRole('button', { name: 'Buat acara sendiri', exact: true }).first().click();
    await heading('Mari buat acara Anda');
    ok('CTA utama langsung membuka alur awal tanpa menu transaksi');
    const oldFlow = await page.evaluate(() => localStorage.getItem('vaksara-connected-demo-v1'));
    await click('Lanjut susun kebutuhan');
    ok('nama kosong ditolak', (await page.getByRole('alert').innerText()).includes('Isi nama'));
    await page.getByLabel('Nama pasangan atau acara', { exact: false }).fill('Pernikahan Ayu & Arif');
    await page.getByLabel('Perkiraan anggaran', { exact: false }).fill('-1000');
    await click('Lanjut susun kebutuhan');
    ok('anggaran negatif ditolak', (await page.getByRole('alert').innerText()).includes('Rupiah bulat'));
    await page.getByLabel('Perkiraan anggaran', { exact: false }).fill('1000.5');
    await click('Lanjut susun kebutuhan');
    ok('anggaran pecahan ditolak', (await page.getByRole('alert').innerText()).includes('Rupiah bulat'));
    await page.getByLabel('Perkiraan anggaran', { exact: false }).fill('50000000');
    await page.getByLabel('Kota atau lokasi acara', { exact: false }).fill('Makassar');
    fs.mkdirSync(path.join(__dirname, 'qa-results'), { recursive: true });
    ok('form ponsel tidak melebar', await fits());
    await click('Lanjut susun kebutuhan');
    await heading('Apa yang Anda butuhkan?');
    ok('tanggal belum pasti diperbolehkan');
    await page.getByLabel('Pemandu prosesi adat', { exact: true }).check();
    await page.getByLabel('Dokumentasi', { exact: true }).check();
    await click('Kembali ke data acara');
    await page.screenshot({ path: path.join(__dirname, 'qa-results/onboarding-step1-mobile.png'), fullPage: true });
    ok('kembali mempertahankan nama', await page.getByLabel('Nama pasangan atau acara', { exact: false }).inputValue() === 'Pernikahan Ayu & Arif');
    await click('Lanjut susun kebutuhan');
    ok('kembali mempertahankan kebutuhan', await page.getByLabel('Dokumentasi', { exact: true }).isChecked());
    await page.reload();
    await heading('Apa yang Anda butuhkan?');
    ok('langkah dan pilihan pulih setelah reload', await page.getByLabel('Dokumentasi', { exact: true }).isChecked());
    await click('Lihat rencana saya');
    await heading('Rencana awal Anda siap');
    ok('ringkasan menunjukkan tanggal belum pasti', await page.getByText('Tanggal belum ditentukan', { exact: true }).isVisible());
    await click('Mulai merencanakan');
    await heading('Pernikahan Ayu & Arif');
    ok('data transaksi lama tidak tertimpa', await page.evaluate(() => localStorage.getItem('vaksara-connected-demo-v1')) === oldFlow);
    ok('home ponsel tidak melebar', await fits());
    await page.screenshot({ path: path.join(__dirname, 'qa-results/onboarding-home-mobile.png'), fullPage: true });
    await page.reload();
    await heading('Pernikahan Ayu & Arif');
    ok('rencana selesai pulih setelah reload');
    await click('Cari pemandu prosesi adat');
    await page.getByLabel('Cari pelaku budaya', { exact: true }).waitFor();
    ok('kebutuhan membuka pencarian relevan', await page.getByLabel('Cari pelaku budaya', { exact: true }).inputValue() === 'prosesi');
    await page.goto(base + 'planner');
    await click('Buka menu');
    ok('menu pengantin ringkas', await page.getByRole('button', { name: /^Kerja sama/ }).first().isVisible());
    await page.getByRole('button', { name: 'Rencana acara', exact: true }).click();
    await heading('Rencana acara');
    await click('Ubah acara dan kebutuhan');
    await heading('Mari buat acara Anda');
    await click('Lanjut susun kebutuhan');
    await click('Lewati, tentukan nanti');
    await heading('Rencana awal Anda siap');
    await click('Mulai merencanakan');
    await heading('Pernikahan Ayu & Arif');
    ok('kebutuhan boleh dilewati', await page.getByRole('button', { name: 'Cari layanan', exact: true }).last().isVisible());
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.screenshot({ path: path.join(__dirname, 'qa-results/onboarding-home-desktop.png'), fullPage: true });
    ok('desktop tidak melebar', await fits());
    await page.evaluate(() => localStorage.setItem('vaksara-event-plan-v1', '{invalid'));
    await page.reload();
    await heading('Mari buat acara Anda');
    ok('data rusak diberitahukan', (await page.getByRole('alert').innerText()).includes('tidak dapat dibaca'));
    ok('data rusak tidak diam-diam ditimpa', await page.evaluate(() => localStorage.getItem('vaksara-event-plan-v1')) === '{invalid');
    await page.evaluate(() => { localStorage.removeItem('vaksara-event-plan-v1'); Storage.prototype.setItem = () => { throw new Error('quota'); }; });
    await page.getByLabel('Nama pasangan atau acara', { exact: false }).fill('Uji penyimpanan');
    await click('Lanjut susun kebutuhan');
    ok('gagal simpan menahan langkah dan memberi penjelasan', (await page.getByRole('alert').innerText()).includes('belum tersimpan') && await page.getByRole('heading', { name: 'Mari buat acara Anda' }).isVisible());
    ok('tanpa runtime error', errors.length === 0);
    fs.writeFileSync(path.join(__dirname, 'qa-results/onboarding.json'), JSON.stringify({ passed, errors }, null, 2));
    console.log('TOTAL ONBOARDING', passed, 'passed');
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exitCode = 1; });
